import { denyWrites, restoreWrites, dismissWithKeyboard, expect, test } from "./fixtures";
const key = "splitstay.group.v1";
test("adds a subset expense, reloads, and confirms removal", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Remove participant Alex", exact: true })).toBeDisabled();
  await page.getByLabel("Description", { exact: true }).fill("Train tickets");
  await page.getByLabel("Amount (EUR)", { exact: true }).fill("10.01");
  await page.getByLabel("Paid by", { exact: true }).selectOption("alex");
  await page.getByRole("checkbox", { name: "Alex", exact: true }).uncheck();
  await page.getByRole("button", { name: "Add expense", exact: true }).click();
  const row = page.getByRole("listitem").filter({ has: page.getByRole("heading", { name: "Train tickets", exact: true }) });
  await expect(row).toContainText("€10.01");
  await row.getByText("Individual shares", { exact: true }).click();
  await expect(row).toContainText("€5.01");
  await expect(row).toContainText("€5.00");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Train tickets", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Remove expense Train tickets", exact: true }).click();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Train tickets", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Remove expense Train tickets", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Remove expense", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Train tickets", exact: true })).toHaveCount(0);
  await page.getByLabel("Participant name", { exact: true }).fill("Dana");
  await page.getByRole("button", { name: "Add participant", exact: true }).click();
  await page.getByRole("button", { name: "Remove participant Dana", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Remove participant", exact: true }).click();
  await expect(page.getByRole("button", { name: "Remove participant Dana", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Train tickets", exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
test("preserves unsupported saved data until reset confirmation", async ({ page }) => {
  const bad = JSON.stringify({ version: 1, participants: [{ id: "a", name: "Alex" }], expenses: [{ id: "e", description: "Broken", payerId: "missing", amountCents: 1, participantIds: ["a"] }] });
  await page.addInitScript(({ key, bad }) => localStorage.setItem(key, bad), { key, bad });
  await page.goto("/");
  await expect(page.getByRole("alert").filter({ hasText: "unsupported format" })).toContainText("unsupported format");
  await expect(page.getByRole("button", { name: "Add expense", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Reset group", exact: true }).click();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(bad);
  await page.getByRole("button", { name: "Reset group", exact: true }).click();
  await page.getByRole("button", { name: "Reset to sample", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Weekend apartment", exact: true })).toBeVisible();
  expect(await page.evaluate(key => localStorage.getItem(key), key)).not.toBe(bad);
});
test("reports repeated write failure, then saves the actual modified group after storage recovers", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Weekend apartment", exact: true })).toBeVisible();
  await denyWrites(page);
  await page.getByLabel("Description", { exact: true }).fill("Recovery train");
  await page.getByLabel("Amount (EUR)", { exact: true }).fill("12.34");
  await page.getByRole("button", { name: "Add expense", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Changes could not be saved" })).toBeVisible();
  await expect(page.getByLabel("Description", { exact: true })).toHaveValue("Recovery train");
  await page.getByRole("button", { name: "Retry saving", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Changes could not be saved" })).toBeVisible();
  await restoreWrites(page);
  await page.getByRole("button", { name: "Retry saving", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toHaveCount(0);
  await expect(page.getByLabel("Description", { exact: true })).toHaveValue("Recovery train");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Recovery train", exact: true })).toBeVisible();
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toContain('"description":"Recovery train"');
});
