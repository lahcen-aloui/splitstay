test("reset keeps drafts and selections on failure, clears them only on successful confirmation", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("Description", { exact: true }).fill("Draft dinner");
  await page.getByLabel("Amount (EUR)", { exact: true }).fill("invalid");
  await page.getByLabel("Participant name", { exact: true }).fill("Draft person");
  await page.getByLabel("Paid by", { exact: true }).selectOption("bea");
  await page.getByRole("checkbox", { name: "Alex", exact: true }).uncheck();
  await page.getByRole("button", { name: "Add expense", exact: true }).click();
  await denyWrites(page);
  await page.getByRole("button", { name: "Reset group", exact: true }).click();
  await page.getByRole("button", { name: "Reset to sample", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByLabel("Description", { exact: true })).toHaveValue("Draft dinner");
  await expect(page.getByLabel("Participant name", { exact: true })).toHaveValue("Draft person");
  await expect(page.getByRole("checkbox", { name: "Alex", exact: true })).not.toBeChecked();
  await expect(page.getByLabel("Paid by", { exact: true })).toHaveValue("bea");
  await restoreWrites(page);
  await page.getByRole("button", { name: "Reset group", exact: true }).click();
  await page.getByRole("button", { name: "Reset to sample", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByLabel("Description", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Amount (EUR)", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Participant name", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Paid by", { exact: true })).toHaveValue("alex");
  await expect(page.getByRole("checkbox", { name: "Alex", exact: true })).toBeChecked();
  await expect(page.getByRole("main").getByRole("alert")).toHaveCount(0);
});
